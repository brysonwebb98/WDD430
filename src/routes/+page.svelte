<h1>Signum Loan Platform</h1>

<p>
	Signum is a loan application and underwriting platform designed to help
	Loan Officers submit applications and Credit Managers review and update
	loan decisions.
</p>

<section>
	<h2>How It Works</h2>
	<p>
		Loan Officers can create and track loan applications. Credit Managers
		can review borrower information, debt-to-income ratio, credit score,
		and make an underwriting decision.
	</p>
</section>

